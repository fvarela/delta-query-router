"""TPC-DS data: generate with DuckDB, write each table once as an external Delta table.

Plain functions. Nothing here reads `.env`: the caller loads it into the environment.
"""

import os
import time
from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Protocol

import duckdb
import pyarrow as pa
from databricks.sdk.errors import NotFound
from databricks.sdk.service.sql import StatementState
from deltalake import DeltaTable, write_deltalake

from dqr.data.unity_catalog import (
    CONTAINER,
    DEFAULT_CATALOG,
    MARKER,
    SettingsError,
    Step,
)

# The 24 TPC-DS data tables (`dbgen_version` is generator metadata and left out).
TABLE_NAMES = (
    "call_center",
    "catalog_page",
    "catalog_returns",
    "catalog_sales",
    "customer",
    "customer_address",
    "customer_demographics",
    "date_dim",
    "household_demographics",
    "income_band",
    "inventory",
    "item",
    "promotion",
    "reason",
    "ship_mode",
    "store",
    "store_returns",
    "store_sales",
    "time_dim",
    "warehouse",
    "web_page",
    "web_returns",
    "web_sales",
    "web_site",
)

WRITE_SETTINGS = ("DQR_STORAGE_ACCOUNT", "AZURE_TENANT_ID")
REGISTER_SETTINGS = ("DQR_STORAGE_ACCOUNT", "DATABRICKS_WAREHOUSE_ID")

BATCH_SIZE = 100_000
STATEMENT_WAIT = "30s"  # how long one call waits before we poll
POLL_SECONDS = 2.0


class WriteError(Exception):
    """Writing stopped; the tables after the failing one were not written."""


class RegisterError(Exception):
    """Registration stopped; the tables after the failing one were not registered."""


@dataclass(frozen=True)
class WriteSettings:
    storage_account: str
    tenant_id: str

    @property
    def root(self) -> str:
        return f"abfss://{CONTAINER}@{self.storage_account}.dfs.core.windows.net/"

    @property
    def storage_options(self) -> dict[str, str]:
        # deltalake logs in through the Azure CLI session of the author.
        return {"azure_use_azure_cli": "true", "azure_tenant_id": self.tenant_id}


def load_write_settings(env: Mapping[str, str] | None = None) -> WriteSettings:
    """Read the settings the write action needs.

    Errors name the missing variables and never show a value.
    """
    env = os.environ if env is None else env
    values = {name: env.get(name, "").strip() for name in WRITE_SETTINGS}
    missing = [name for name, value in values.items() if not value]
    if missing:
        raise SettingsError(f"missing settings: {', '.join(missing)}")
    return WriteSettings(
        storage_account=values["DQR_STORAGE_ACCOUNT"],
        tenant_id=values["AZURE_TENANT_ID"],
    )


class Source(Protocol):
    def table_names(self) -> list[str]: ...

    def row_count(self, name: str) -> int: ...

    def reader(self, name: str) -> pa.RecordBatchReader: ...


class DuckDbSource:
    """TPC-DS tables generated by DuckDB's `dsdgen` in an in-memory database."""

    def __init__(self, scale_factor: float):
        self._con = duckdb.connect()
        self._con.sql("INSTALL tpcds")
        self._con.sql("LOAD tpcds")
        self._con.sql(f"CALL dsdgen(sf={float(scale_factor)})")

    def table_names(self) -> list[str]:
        return [row[0] for row in self._con.sql("SHOW TABLES").fetchall()]

    def row_count(self, name: str) -> int:
        return self._con.sql(f'SELECT count(*) FROM "{name}"').fetchall()[0][0]

    def reader(self, name: str) -> pa.RecordBatchReader:
        return self._con.sql(f'SELECT * FROM "{name}"').to_arrow_reader(BATCH_SIZE)


def _table_path(root: str, schema: str, name: str) -> str:
    return f"{root.rstrip('/')}/{schema}/{name}"


def _logged_row_count(path: str, storage_options: dict[str, str] | None) -> int:
    """The number of rows the Delta log records for the table at `path`."""
    actions = DeltaTable(path, storage_options=storage_options).get_add_actions()
    return sum(pa.table(actions)["num_records"].to_pylist())


def write_tables(
    source: Source,
    root: str,
    schema: str,
    storage_options: dict[str, str] | None = None,
) -> list[Step]:
    """Write each missing table once under `<root>/<schema>/<table>/` and report.

    A folder that already holds a Delta table is skipped, never overwritten. After each
    write, the row count in the Delta log must equal the source's, or writing stops.
    """
    if sorted(source.table_names()) != sorted(TABLE_NAMES):
        raise WriteError("the source does not provide exactly the 24 TPC-DS tables")

    report = []
    for name in TABLE_NAMES:
        full_name = f"{schema}.{name}"
        path = _table_path(root, schema, name)
        if DeltaTable.is_deltatable(path, storage_options=storage_options):
            report.append(Step("table", full_name, "exists"))
            continue
        expected = source.row_count(name)
        write_deltalake(
            path, source.reader(name), mode="error", storage_options=storage_options
        )
        logged = _logged_row_count(path, storage_options)
        if logged != expected:
            raise WriteError(
                f"table {full_name}: the Delta log has {logged} rows, "
                f"the source has {expected}"
            )
        report.append(Step("table", full_name, f"written, {logged} rows"))
    return report


@dataclass(frozen=True)
class RegisterSettings:
    storage_account: str
    warehouse_id: str
    catalog: str = DEFAULT_CATALOG

    @property
    def root(self) -> str:
        return f"abfss://{CONTAINER}@{self.storage_account}.dfs.core.windows.net/"


def load_register_settings(env: Mapping[str, str] | None = None) -> RegisterSettings:
    """Read the settings the register action needs.

    Errors name the missing variables and never show a value.
    """
    env = os.environ if env is None else env
    values = {name: env.get(name, "").strip() for name in REGISTER_SETTINGS}
    missing = [name for name, value in values.items() if not value]
    if missing:
        raise SettingsError(f"missing settings: {', '.join(missing)}")
    return RegisterSettings(
        storage_account=values["DQR_STORAGE_ACCOUNT"],
        warehouse_id=values["DATABRICKS_WAREHOUSE_ID"],
        catalog=env.get("DQR_CATALOG", "").strip() or DEFAULT_CATALOG,
    )


def _existing_table(client, full_name: str):
    try:
        return client.tables.get(full_name)
    except NotFound:
        return None


def _run_statement(client, settings: RegisterSettings, statement: str, sleep):
    """Send one statement and wait until it is no longer pending or running."""
    result = client.statement_execution.execute_statement(
        statement=statement,
        warehouse_id=settings.warehouse_id,
        wait_timeout=STATEMENT_WAIT,
    )
    while result.status.state in (StatementState.PENDING, StatementState.RUNNING):
        sleep(POLL_SECONDS)
        result = client.statement_execution.get_statement(result.statement_id)
    return result.status


def register_tables(
    client,
    settings: RegisterSettings,
    schema: str,
    sleep: Callable[[float], None] = time.sleep,
) -> list[Step]:
    """Register each missing table as an external Delta table and report.

    All lookups run before the first statement, so a table that exists without our
    marker stops registration cleanly. A failed statement stops it; a rerun resumes.
    """
    catalog = settings.catalog
    found = {}
    for name in TABLE_NAMES:
        full_name = f"{catalog}.{schema}.{name}"
        table = _existing_table(client, full_name)
        if table is not None and getattr(table, "comment", None) != MARKER:
            raise RegisterError(
                f"table {full_name} already exists and was not created by this "
                "tool; nothing was changed"
            )
        found[name] = table

    report = []
    for name in TABLE_NAMES:
        full_name = f"{catalog}.{schema}.{name}"
        if found[name] is not None:
            report.append(Step("table", full_name, "exists"))
            continue
        statement = (
            f"CREATE TABLE `{catalog}`.`{schema}`.`{name}` USING DELTA "
            f"COMMENT '{MARKER}' LOCATION '{settings.root}{schema}/{name}/'"
        )
        status = _run_statement(client, settings, statement, sleep)
        if status.state != StatementState.SUCCEEDED:
            message = status.error.message if status.error else status.state.value
            raise RegisterError(f"table {full_name}: {message}")
        report.append(Step("table", full_name, "registered"))
    return report
